"""Tests for the runtime Bitwise-Cyclic-Tag interpreter written in S5 (bct/).

Every test runs the *actual* S5 executor (in-process, like the ctag/ suite)
with the machine generated by bct._gen_bct.build_interpreter, feeding the
BCT instance (plen, program bits, dlen, data bits) through stdin, and checks
the resulting tick counter against the definitional reference in
bct.reference.

The interpreter is *constant size*: the same fixed bct/s/bct.s5 executes any
BCT machine, growing the universe at runtime as the data buffer expands.
"""
import io
import os
import random
import subprocess
import sys
import contextlib
from pathlib import Path

HERE = Path(__file__).parent
ROOT = HERE.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))

